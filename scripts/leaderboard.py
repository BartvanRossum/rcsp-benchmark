#!/usr/bin/env python3
"""Leaderboard maintenance for the RCSP benchmark.

Commands
--------
  seed            Build docs/data/leaderboard.json from the table in solutions/README.md.
  render-readme   Regenerate the best-known-solutions table in solutions_dashboard/README.md.
  process         Check a solution submitted through the issue form and, if it is
                  feasible and strictly cheaper than the current best known upper
                  bound, store it and update the leaderboard.

Submitted solutions are stored in solutions_dashboard/; solutions/ keeps the paper's
solutions and is never modified. Only upper bounds are updated by submissions. Root and best lower bounds are the
values reported in the accompanying paper and are never changed by this script.
"""

from __future__ import annotations

import argparse
import datetime as dt
import json
import os
import re
import subprocess
import sys
import urllib.parse
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
INSTANCES = ROOT / "instances"
PAPER_README = ROOT / "solutions" / "README.md"          # paper results; never modified
SOLUTIONS = ROOT / "solutions_dashboard"                  # best known solutions, updated by submissions
SOLUTIONS_README = SOLUTIONS / "README.md"
DATA = ROOT / "docs" / "data" / "leaderboard.json"
CHECKER = ROOT / "checker.jar"

REPO = os.environ.get("GITHUB_REPOSITORY", "BartvanRossum/rcsp-benchmark")
VARIANTS = {"single": "Single-depot", "multi": "Multi-depot"}
GROUPS = [("Tiny", 0, 500), ("Small", 500, 1000), ("Medium", 1000, 2000), ("Large", 2000, 10**9)]

TABLE_START = "<!-- BKS-TABLE:START (generated by scripts/leaderboard.py, do not edit by hand) -->"
TABLE_END = "<!-- BKS-TABLE:END -->"

MAX_BYTES = 5 * 1024 * 1024
MAX_LINES = 20000
CHECKER_TIMEOUT = 900
ALLOWED_HOSTS = {"github.com", "user-images.githubusercontent.com",
                 "objects.githubusercontent.com", "private-user-images.githubusercontent.com"}

PAPER_HOLDER = {
    "name": "B.T.C. van Rossum",
    "github": "BartvanRossum",
    "method": "Branch and price (paper experiments)",
    "reference": "https://arxiv.org/abs/2606.10081",
}


# --------------------------------------------------------------------------- helpers

def instance_key(name: str) -> tuple[int, int]:
    m = re.fullmatch(r"s(\d+)_t(\d+)", name)
    return (int(m.group(2)), int(m.group(1))) if m else (10**9, 0)


def group_of(tasks: int) -> str:
    for g, lo, hi in GROUPS:
        if lo <= tasks < hi:
            return g
    return "Large"


def gap(ub: int, lb: int) -> float:
    return round((ub - lb) / ub * 100, 2) if ub else 0.0


def fmt_int(x: int) -> str:
    return f"{x:,}"


def fmt_gap(ub: int, lb: int) -> str:
    return "0" if ub <= lb else f"{gap(ub, lb):.2f}"


def solution_path(variant: str, inst: str) -> Path:
    return SOLUTIONS / f"{variant}_depot" / f"solution_{variant}_depot_{inst}.txt"


def load() -> dict:
    return json.loads(DATA.read_text())


def save(data: dict) -> None:
    data["updated"] = now()
    if os.environ.get("GITHUB_REPOSITORY"):
        data["repo"] = os.environ["GITHUB_REPOSITORY"]
    DATA.parent.mkdir(parents=True, exist_ok=True)
    DATA.write_text(json.dumps(data, indent=1, ensure_ascii=False) + "\n")


def now() -> str:
    return dt.datetime.now(dt.timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


# --------------------------------------------------------------------------- seed

def cmd_seed(_args) -> None:
    text = PAPER_README.read_text()
    rows = re.findall(r"<tr>\s*<td><code>(\S+)</code></td>(.*?)</tr>", text, re.S)
    if not rows:
        sys.exit("No table rows found in solutions/README.md")
    instances = []
    for name, body in rows:
        v = [int(x.replace(",", "")) if i % 5 != 3 else float(x)
             for i, x in enumerate(re.findall(r'<td align="right">(.*?)</td>', body))]
        tasks = instance_key(name)[0]
        entry = {"name": name, "stations": instance_key(name)[1], "tasks": tasks, "group": group_of(tasks)}
        for k, var in ((0, "single"), (5, "multi")):
            root_lb, lb, ub, g, duties = v[k:k + 5]
            entry[var] = {"root_lb": root_lb, "best_lb": lb, "best_ub": ub, "gap": gap(ub, lb),
                          "duties": duties, "holder": PAPER_HOLDER, "date": None, "issue": None}
        instances.append(entry)
    save({"repo": REPO, "instances": instances, "history": []})
    print(f"Seeded {len(instances)} instances into {DATA.relative_to(ROOT)}")


# --------------------------------------------------------------------------- README table

def render_table(data: dict) -> str:
    out = ["<table>", "<thead>", "<tr>", '<th rowspan="2">Instance</th>',
           '<th colspan="5">Single-depot</th>', '<th colspan="5">Multi-depot</th>', "</tr>", "<tr>"]
    out += ["<th>Root LB</th>", "<th>Best LB</th>", "<th>Best UB</th>", "<th>Gap (%)</th>", "<th>Duties</th>"] * 2
    out += ["</tr>", "</thead>", "<tbody>"]
    for e in data["instances"]:
        out += ["<tr>", f"<td><code>{e['name']}</code></td>"]
        for var in ("single", "multi"):
            r = e[var]
            for val in (fmt_int(r["root_lb"]), fmt_int(r["best_lb"]), fmt_int(r["best_ub"]),
                        fmt_gap(r["best_ub"], r["best_lb"]), str(r["duties"])):
                out.append(f'<td align="right">{val}</td>')
        out.append("</tr>")
    out += ["</tbody>", "</table>"]
    return "\n".join(out)


def cmd_render_readme(_args) -> None:
    data = load()
    text = SOLUTIONS_README.read_text()
    table = f"{TABLE_START}\n{render_table(data)}\n{TABLE_END}"
    if TABLE_START not in text:
        sys.exit(f"Table markers not found in {SOLUTIONS_README.relative_to(ROOT)}")
    text = re.sub(re.escape(TABLE_START) + r".*?" + re.escape(TABLE_END), lambda _: table, text, flags=re.S)
    SOLUTIONS_README.write_text(text if text.endswith("\n") else text + "\n")
    print(f"Rendered table in {SOLUTIONS_README.relative_to(ROOT)}")


# --------------------------------------------------------------------------- issue parsing

def parse_issue_form(body: str) -> dict[str, str]:
    """Split a GitHub issue-form body ('### Label\\n\\nvalue') into {label: value}."""
    fields: dict[str, str] = {}
    parts = re.split(r"^### +(.+?)\s*$", body.replace("\r\n", "\n"), flags=re.M)
    for i in range(1, len(parts) - 1, 2):
        value = parts[i + 1].strip()
        fields[parts[i].strip()] = "" if value == "_No response_" else value
    return fields


class Rejected(Exception):
    pass


def extract_solution(field: str) -> str:
    links = re.findall(r"\((https?://[^\s)]+)\)|(https?://\S+)", field)
    urls = [a or b for a, b in links]
    if urls:
        url = urls[0].rstrip(">")
        host = urllib.parse.urlparse(url).hostname or ""
        if url.startswith("http://") or host not in ALLOWED_HOSTS:
            raise Rejected(f"The solution link must be a file attached to the issue on GitHub (got host `{host}`).")
        raw = download(url)
        if len(raw) > MAX_BYTES:
            raise Rejected("The attached file is larger than 5 MB.")
        try:
            return raw.decode("utf-8-sig")
        except UnicodeDecodeError as exc:
            raise Rejected("The attached file is not a plain-text file.") from exc
    # pasted content, possibly in a code fence
    return re.sub(r"^```[^\n]*\n?|\n?```\s*$", "", field.strip())


class _DropAuthOnRedirect(urllib.request.HTTPRedirectHandler):
    """Attachments redirect to a signed storage URL; never forward the token there."""

    def redirect_request(self, req, fp, code, msg, headers, newurl):
        new = super().redirect_request(req, fp, code, msg, headers, newurl)
        if new is not None and urllib.parse.urlparse(newurl).hostname != "github.com":
            new.remove_header("Authorization")
        return new


def download(url: str) -> bytes:
    headers = {"User-Agent": "rcsp-benchmark-leaderboard"}
    token = os.environ.get("GITHUB_TOKEN")
    if token and urllib.parse.urlparse(url).hostname == "github.com":
        headers["Authorization"] = f"Bearer {token}"  # needed for attachments in private repositories
    opener = urllib.request.build_opener(_DropAuthOnRedirect)
    try:
        with opener.open(urllib.request.Request(url, headers=headers), timeout=60) as resp:
            raw = resp.read(MAX_BYTES + 1)
    except Exception as exc:  # noqa: BLE001
        raise Rejected(f"Could not download the attached file ({exc}). "
                       "You can also paste the file contents into the form instead.") from exc
    if raw.lstrip()[:15].lower().startswith((b"<!doctype", b"<html")):
        raise Rejected("Could not download the attached file (got a web page instead of the file). "
                       "You can also paste the file contents into the form instead.")
    return raw


def normalise_solution(text: str) -> list[str]:
    lines = [ln.split() for ln in text.replace("\r\n", "\n").split("\n")]
    lines = [ln for ln in lines if ln]
    if not lines:
        raise Rejected("The solution is empty. Attach the `.txt` file or paste its contents.")
    if len(lines) > MAX_LINES:
        raise Rejected(f"The solution has more than {MAX_LINES} duties.")
    for n, ln in enumerate(lines, 1):
        if not all(tok.isdigit() for tok in ln):
            raise Rejected(f"Line {n} is not a space-separated list of connection indices: `{' '.join(ln)[:80]}`")
    return [" ".join(ln) for ln in lines]


def run_checker(inst: str, sol_file: Path, variant: str) -> tuple[bool, int | None, str]:
    try:
        proc = subprocess.run(["java", "-jar", str(CHECKER), str(INSTANCES / inst), str(sol_file), variant],
                              capture_output=True, text=True, timeout=CHECKER_TIMEOUT)
    except subprocess.TimeoutExpired as exc:
        raise Rejected(f"The checker did not finish within {CHECKER_TIMEOUT // 60} minutes.") from exc
    out = proc.stdout + proc.stderr
    feas = re.findall(r"^FEASIBLE:\s*(true|false)", out, re.M)
    cost = re.findall(r"^COST:\s*(-?\d+)", out, re.M)
    feasible = bool(feas) and feas[-1] == "true" and proc.returncode == 0
    return feasible, int(cost[-1]) if cost else None, out


def checker_summary(out: str, limit: int = 40) -> str:
    """Keep the lines that explain an infeasibility, plus the summary lines."""
    lines = out.splitlines()
    keep, current = [], None
    for ln in lines:
        if ln.startswith("FEASIBILITY CHECK OF DUTY"):
            current = ln
        elif re.search(r":\s*false\b", ln) or re.search(r"(exception|error)", ln, re.I):
            if current and ln.startswith("Duty is feasible"):
                keep.append(current)
            keep.append(ln)
    keep += [ln for ln in lines if re.match(r"^(FEASIBLE|COST):", ln) and ln not in keep]
    if not keep:
        keep = lines[-limit:]
    if len(keep) > limit:
        keep = keep[:limit] + [f"... ({len(keep) - limit} more lines)"]
    return "\n".join(keep)


# --------------------------------------------------------------------------- process

def cmd_process(args) -> None:
    body = os.environ.get("ISSUE_BODY", "")
    author = os.environ.get("ISSUE_AUTHOR", "")
    issue = int(os.environ.get("ISSUE_NUMBER", "0") or 0)
    result: dict = {"status": "rejected", "labels": ["submission"]}
    try:
        result.update(process_submission(body, author, issue))
    except Rejected as exc:
        result.update(status="rejected", reason=str(exc), labels=["submission", "rejected"])
    result["comment"] = compose_comment(result)
    Path(args.out).write_text(json.dumps(result, indent=1))
    print(json.dumps({k: v for k, v in result.items() if k != "comment"}, indent=1))


def process_submission(body: str, author: str, issue: int) -> dict:
    f = parse_issue_form(body)
    inst = f.get("Instance", "").strip().strip("`").lower()
    variant_label = f.get("Variant", "").strip()
    vl = variant_label.lower().strip("` ")
    variant = "single" if vl.startswith("single") else "multi" if vl.startswith("multi") else None
    if not re.fullmatch(r"s\d+_t\d+", inst) or not (INSTANCES / inst).is_dir():
        raise Rejected(f"Unknown instance `{inst[:40]}`. Please pick one from the list.")
    if variant is None:
        raise Rejected("Please choose the variant: Single-depot or Multi-depot.")
    base = {"instance": inst, "variant": variant}

    lines = normalise_solution(extract_solution(f.get("Solution file", "")))
    content = "\n".join(lines) + "\n"
    tmp = ROOT / ".submission.txt"
    tmp.write_text(content)
    try:
        feasible, cost, out = run_checker(inst, tmp, variant)
    finally:
        tmp.unlink(missing_ok=True)

    data = load()
    entry = next(e for e in data["instances"] if e["name"] == inst)
    rec = entry[variant]
    base.update(cost=cost, duties=len(lines), previous_ub=rec["best_ub"], best_lb=rec["best_lb"],
                checker=checker_summary(out))

    if not re.search(r"^FEASIBLE:", out, re.M):
        # The checker crashed or printed nothing useful: our problem, not the submitter's.
        return {**base, "status": "review", "labels": ["submission", "needs-review"],
                "reason": "The checker could not run on this submission. This is a problem on our side; "
                          "a maintainer will look at it."}
    if not feasible or cost is None:
        return {**base, "status": "rejected", "labels": ["submission", "infeasible"],
                "reason": "The checker reports that the solution is infeasible."}
    if cost < rec["best_lb"]:
        # Lower bounds are proven; a cheaper feasible solution means something is off.
        return {**base, "status": "review", "labels": ["submission", "needs-review"],
                "reason": "The cost is below the proven lower bound, so a maintainer will look at it."}
    if cost >= rec["best_ub"]:
        return {**base, "status": "not-better", "labels": ["submission", "not-improving"],
                "reason": "The solution is feasible but not strictly cheaper than the best known solution."}

    holder = {
        "name": f.get("Name", "").strip()[:100] or author,
        "github": author,
        "affiliation": f.get("Affiliation", "").strip()[:150],
        "method": f.get("Method", "").strip()[:300],
        "reference": first_url(f.get("Reference", "")),
    }
    holder = {k: v for k, v in holder.items() if v}
    date = now()
    data["history"].insert(0, {"instance": inst, "variant": variant, "previous_ub": rec["best_ub"],
                               "new_ub": cost, "best_lb": rec["best_lb"], "duties": len(lines),
                               "holder": holder, "date": date, "issue": issue})
    rec.update(best_ub=cost, gap=gap(cost, rec["best_lb"]), duties=len(lines), holder=holder,
               date=date, issue=issue)
    save(data)
    solution_path(variant, inst).write_text(content)
    cmd_render_readme(None)
    return {**base, "status": "accepted", "labels": ["submission", "new-best"], "gap": rec["gap"],
            "commit_message": f"New best {VARIANTS[variant].lower()} solution for {inst}: "
                              f"{fmt_int(base['previous_ub'])} -> {fmt_int(cost)} (#{issue})"}


def first_url(text: str) -> str:
    m = re.search(r"https?://[^\s)>\]]+", text)
    return m.group(0)[:300] if m else ""


def compose_comment(r: dict) -> str:
    inst, var = r.get("instance"), VARIANTS.get(r.get("variant", ""), "")
    head = {"accepted": "### ✅ New best known solution",
            "not-better": "### Feasible, but not an improvement",
            "review": "### ⚠️ Needs a maintainer's review",
            "rejected": "### ❌ Submission rejected"}[r["status"]]
    parts = [head, ""]
    if inst:
        parts.append(f"**Instance:** `{inst}` ({var})  ")
    if r.get("cost") is not None:
        parts.append(f"**Cost:** {fmt_int(r['cost'])} with {r['duties']} duties  ")
        parts.append(f"**Previous best:** {fmt_int(r['previous_ub'])}  ")
        parts.append(f"**Best lower bound:** {fmt_int(r['best_lb'])}  ")
    if r["status"] == "accepted":
        parts += [f"**New gap:** {fmt_gap(r['cost'], r['best_lb'])}%", "",
                  "Thanks! Your solution has been added to the repository and the leaderboard. "
                  "The dashboard updates within a few minutes."]
    else:
        parts += ["", r.get("reason", "")]
        if r["status"] == "rejected":
            parts += ["", "You can edit this issue to correct the submission; it will be checked again."]
    if r.get("checker") and r["status"] != "accepted":
        parts += ["", "<details><summary>Checker output</summary>", "", "```", r["checker"], "```", "", "</details>"]
    return "\n".join(parts)


# --------------------------------------------------------------------------- main

def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    sub.add_parser("seed").set_defaults(func=cmd_seed)
    sub.add_parser("render-readme").set_defaults(func=cmd_render_readme)
    p = sub.add_parser("process")
    p.add_argument("--out", default="result.json")
    p.set_defaults(func=cmd_process)
    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
